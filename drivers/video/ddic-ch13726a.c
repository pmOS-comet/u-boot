	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	int ret;

	plat->lanes = 4;
	plat->format = MIPI_DSI_FMT_RGB888;
	plat->mode_flags = MIPI_DSI_MODE_VIDEO | MIPI_DSI_CLOCK_NON_CONTINUOUS;

	 ret = gpio_request_by_name(dev, "reset-gpio", 0, &priv->reset,
                    GPIOD_IS_OUT);
